"""
Pull Request delivery.

After a patch passes validation, push it to a new branch on the user's GitHub
repository and open a PR from the user's account (via their OAuth token).

A PR is only opened when all preconditions hold (see db.get_pr_eligible_patch):
the fix_job exists, the patch exists, patches.validation_passed = TRUE and
fix_jobs.status = 'awaiting_approval'.
"""
from __future__ import annotations

import asyncio
import json
import re
from typing import Any

import httpx

from .. import db
from ..indexing.github_client import create_pull_request
from ..utils.git_utils import apply_patch_git, diff_changed_files, run_git
from ..utils.logging import get_logger

logger = get_logger("delivery.pull_request")


class PullRequestError(Exception):
    """Raised when branch push or PR creation fails."""


def _redact(text: str, token: str | None) -> str:
    """Strip the OAuth token from git/GitHub output before logging or storing it."""
    return text.replace(token, "***") if token else text


def _parsed_data(signal_row: dict[str, Any] | None) -> dict[str, Any]:
    data = (signal_row or {}).get("parsed_data") or {}
    if isinstance(data, str):
        try:
            data = json.loads(data)
        except ValueError:
            data = {}
    return data if isinstance(data, dict) else {}


def build_branch_name(job_id: str, signal_row: dict[str, Any] | None) -> str:
    """e.g. autofix/issue-42-1a2b3c4d, autofix/ci-987654-1a2b3c4d, autofix/job-1a2b3c4d."""
    short_id = job_id.replace("-", "")[:8]
    ref = re.sub(r"[^A-Za-z0-9._-]", "-", str((signal_row or {}).get("source_ref") or ""))
    signal_type = (signal_row or {}).get("type")
    if signal_type == "github_issue" and ref:
        return f"autofix/issue-{ref}-{short_id}"
    if signal_type == "ci_failure" and ref:
        return f"autofix/ci-{ref}-{short_id}"
    return f"autofix/job-{short_id}"


def build_pr_text(
    job_id: str,
    signal_row: dict[str, Any] | None,
    patch: dict[str, Any],
) -> tuple[str, str]:
    """Return (title, body) for the pull request."""
    data = _parsed_data(signal_row)
    signal_type = (signal_row or {}).get("type")
    explanation = (patch.get("explanation") or "").strip() or "Automated fix generated by AutoFix."

    if signal_type == "github_issue":
        issue_title = data.get("title") or f"issue #{signal_row.get('source_ref')}"
        title = f"fix: {issue_title}"
        closes = f"Fixes #{data.get('number') or signal_row.get('source_ref')}\n\n"
    elif signal_type == "ci_failure":
        title = f"fix: CI failure in {data.get('workflow_name') or 'workflow'}"
        run_url = data.get("html_url")
        closes = f"Fixes failing workflow run: {run_url}\n\n" if run_url else ""
    else:
        title = "fix: automated fix by AutoFix"
        closes = ""

    log_tail = (patch.get("validation_log") or "").strip()[-3000:]
    body = (
        f"{closes}"
        f"## Summary\n{explanation}\n\n"
        f"## Validation\n"
        f"Patch passed sandbox validation on attempt {patch.get('attempt_number')}.\n\n"
        f"<details><summary>Validation log</summary>\n\n```\n{log_tail or '(no output)'}\n```\n</details>\n\n"
        f"---\n_Generated by AutoFix (job `{job_id}`). Please review before merging._"
    )
    return title[:250], body


def commit_and_push_branch(
    repo_path: str,
    branch: str,
    diff_content: str,
    commit_message: str,
    author_name: str,
    author_email: str,
) -> None:
    """
    Create `branch` from the current HEAD of the clone at repo_path, apply the
    diff, commit it as the given author and push to origin.
    Raises PullRequestError on any failure.
    """
    code, _, err = run_git(["checkout", "-b", branch], cwd=repo_path)
    if code != 0:
        raise PullRequestError(f"git checkout -b {branch} failed: {err}")

    ok, msg = apply_patch_git(repo_path, diff_content)
    if not ok:
        raise PullRequestError(f"Patch did not apply on a fresh branch: {msg}")

    # Stage only the files the diff touches: the clone may also contain
    # validation artefacts (node_modules, `patch` .orig/.rej backups, ...).
    paths = diff_changed_files(diff_content)
    if not paths:
        raise PullRequestError("Could not determine which files the patch changes.")
    code, _, err = run_git(["add", "-A", "--", *paths], cwd=repo_path)
    if code != 0:
        raise PullRequestError(f"git add failed: {err}")
    code, _, _ = run_git(["diff", "--cached", "--quiet"], cwd=repo_path)
    if code == 0:
        raise PullRequestError("Patch produced no changes to commit.")

    code, _, err = run_git(
        [
            "-c", f"user.name={author_name}",
            "-c", f"user.email={author_email}",
            "commit", "-m", commit_message,
        ],
        cwd=repo_path,
    )
    if code != 0:
        raise PullRequestError(f"git commit failed: {err}")

    code, _, err = run_git(["push", "origin", f"HEAD:refs/heads/{branch}"], cwd=repo_path)
    if code != 0:
        raise PullRequestError(f"git push failed: {err}")


async def create_pull_request_for_job(
    job_id: str,
    patch_id: str,
    repo_path: str,
    repo_row: dict[str, Any],
    signal_row: dict[str, Any] | None,
) -> str | None:
    """
    Push the validated patch to a new branch and open a PR as the repo owner.

    `repo_path` must be a clean clone of the default branch whose `origin`
    remote is authenticated with the owner's token.

    Returns the PR URL, or None if the PR preconditions are not met.
    Raises PullRequestError if pushing or opening the PR fails.
    """
    patch = await db.get_pr_eligible_patch(job_id, patch_id)
    if patch is None:
        logger.warning(
            "[Job %s] PR preconditions not met for patch #%s "
            "(need fix_job + patch, validation_passed=TRUE, status='awaiting_approval'). Skipping PR.",
            job_id, patch_id,
        )
        return None

    existing = await db.get_pull_request_for_job(job_id)
    if existing:
        logger.info("[Job %s] PR already exists: %s", job_id, existing["pr_url"])
        return existing["pr_url"]

    token = repo_row.get("github_access_token") or ""
    owner, name = repo_row["owner"], repo_row["name"]
    base = repo_row.get("default_branch") or "main"
    username = repo_row.get("github_username") or "autofix"
    author_email = (
        f"{repo_row['github_id']}+{username}@users.noreply.github.com"
        if repo_row.get("github_id") else f"{username}@users.noreply.github.com"
    )

    branch = build_branch_name(job_id, signal_row)
    title, body = build_pr_text(job_id, signal_row, patch)

    logger.info("[Job %s] Pushing patch #%s to branch %s on %s/%s", job_id, patch_id, branch, owner, name)
    try:
        # git subprocesses are blocking — keep them off the event loop
        await asyncio.to_thread(
            commit_and_push_branch,
            repo_path, branch, patch["diff_content"], title, username, author_email,
        )
    except PullRequestError as e:
        raise PullRequestError(_redact(str(e), token)) from None

    async with httpx.AsyncClient(timeout=30.0) as http:
        try:
            pr = await create_pull_request(http, owner, name, token, branch, base, title, body)
        except (RuntimeError, httpx.HTTPError) as e:
            raise PullRequestError(_redact(str(e), token)) from None

    await db.insert_pull_request(job_id, patch_id, pr["number"], pr["html_url"])
    logger.info("[Job %s] Opened PR #%s: %s", job_id, pr["number"], pr["html_url"])
    return pr["html_url"]
