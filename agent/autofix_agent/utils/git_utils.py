"""
Shared low-level git subprocess helpers.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
from typing import Sequence

from .logging import get_logger

logger = get_logger("git_utils")


def run_git(
    args: Sequence[str],
    cwd: str | None = None,
    check: bool = False,
) -> tuple[int, str, str]:
    """
    Execute a git command using subprocess.

    Returns:
        tuple (returncode, stdout, stderr)
    """
    cmd = ["git"] + list(args)
    logger.debug("Executing git command: %s (cwd=%s)", " ".join(cmd), cwd)

    proc = subprocess.run(
        cmd,
        cwd=cwd,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )

    if check and proc.returncode != 0:
        err_msg = f"Git command failed: {' '.join(cmd)}\nSTDERR: {proc.stderr}\nSTDOUT: {proc.stdout}"
        logger.error(err_msg)
        raise RuntimeError(err_msg)

    return proc.returncode, proc.stdout.strip(), proc.stderr.strip()


def get_head_sha(repo_path: str) -> str:
    """Return the current HEAD commit SHA of the repository."""
    code, stdout, stderr = run_git(["rev-parse", "HEAD"], cwd=repo_path, check=True)
    return stdout.strip()


def get_diff_name_status(
    repo_path: str,
    old_sha: str | None,
    new_sha: str,
) -> list[tuple[str, str]]:
    """
    Run `git diff --name-status <old_sha> <new_sha>`.

    Returns a list of tuples: [(status_code, file_path), ...]
    where status_code is 'A', 'M', 'D', 'R', etc.
    """
    if not old_sha:
        # If no previous sha, list all tracked files as Added ('A')
        code, stdout, stderr = run_git(["ls-files"], cwd=repo_path, check=True)
        files = [line.strip() for line in stdout.splitlines() if line.strip()]
        return [("A", f) for f in files]

    args = ["diff", "--name-status", old_sha, new_sha]
    code, stdout, stderr = run_git(args, cwd=repo_path, check=True)

    results: list[tuple[str, str]] = []
    for line in stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split("\t")
        if len(parts) >= 2:
            status = parts[0][0].upper()  # 'A', 'M', 'D', 'R'
            # If renamed, parts can be [R100, old_path, new_path]
            path = parts[-1]
            results.append((status, path))

    return results


def clone_repo(
    clone_url: str,
    target_dir: str,
    branch: str = "main",
) -> str:
    """Clone a git repository to target_dir."""
    os.makedirs(os.path.dirname(os.path.abspath(target_dir)), exist_ok=True)
    if os.path.exists(target_dir):
        logger.info("Target directory %s already exists, skipping clone.", target_dir)
        return target_dir

    logger.info("Cloning %s (branch: %s) -> %s", clone_url, branch, target_dir)
    args = ["clone", "--branch", branch, clone_url, target_dir]
    run_git(args, check=True)
    return target_dir


def pull_repo(repo_path: str, branch: str = "main") -> str:
    """Pull latest changes from origin branch."""
    logger.info("Pulling latest git changes in %s (branch: %s)", repo_path, branch)
    run_git(["checkout", branch], cwd=repo_path, check=False)
    run_git(["pull", "origin", branch], cwd=repo_path, check=True)
    return get_head_sha(repo_path)


def normalize_diff(diff_str: str) -> str:
    """Clean and repair unified diffs generated by LLMs."""
    cleaned = diff_str.strip()
    # Strip markdown code blocks if the LLM wrapped it in ```diff ... ```
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```[a-zA-Z0-9_\-]*\n", "", cleaned)
        cleaned = re.sub(r"\n```$", "", cleaned)

    lines = cleaned.splitlines()
    repaired_lines = []
    in_hunk = False

    for line in lines:
        if line.startswith("@@"):
            in_hunk = True
            repaired_lines.append(line)
        elif in_hunk:
            if line.startswith("---") or line.startswith("+++") or line.startswith("diff"):
                in_hunk = False
                repaired_lines.append(line)
            elif line.startswith("+") or line.startswith("-") or line.startswith(" ") or line.startswith("\\"):
                repaired_lines.append(line)
            else:
                # Missing leading space on context line
                repaired_lines.append(" " + line)
        else:
            repaired_lines.append(line)

    return "\n".join(repaired_lines) + "\n"


def apply_patch_git(
    repo_path: str,
    patch_content: str,
    check_only: bool = False,
) -> tuple[bool, str]:
    """
    Apply a unified diff patch using git apply with multiple recovery strategies:
    1. Standard git apply
    2. git apply with --recount, --ignore-space-change, --ignore-whitespace
    3. patch -p1 fallback (GNU/BSD patch utility)
    """
    normalized_patch = normalize_diff(patch_content)

    # 1. Standard git apply
    cmd = ["git", "apply"]
    if check_only:
        cmd.append("--check")
    cmd.append("-")

    proc = subprocess.run(
        cmd,
        cwd=repo_path,
        input=normalized_patch,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if proc.returncode == 0:
        return True, "Patch applied successfully."

    # 2. git apply with --recount and whitespace tolerance
    recount_cmd = ["git", "apply", "--recount", "--ignore-space-change", "--ignore-whitespace", "--inaccurate-eof"]
    if check_only:
        recount_cmd.append("--check")
    recount_cmd.append("-")

    recount_proc = subprocess.run(
        recount_cmd,
        cwd=repo_path,
        input=normalized_patch,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if recount_proc.returncode == 0:
        return True, "Patch applied with --recount and whitespace tolerance."

    # 3. patch utility fallback (very forgiving of LLM header miscounts)
    if not check_only:
        patch_bin = shutil.which("patch") or "/usr/bin/patch"
        if os.path.exists(patch_bin):
            patch_cmd = [patch_bin, "-p1", "--batch", "--forward", "-N"]
            p_proc = subprocess.run(
                patch_cmd,
                cwd=repo_path,
                input=normalized_patch,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
            )
            if p_proc.returncode == 0:
                return True, "Patch applied with patch utility."

    err = f"git apply failed:\nSTDOUT: {proc.stdout}\nSTDERR: {proc.stderr}\nRecount STDERR: {recount_proc.stderr}"
    return False, err
